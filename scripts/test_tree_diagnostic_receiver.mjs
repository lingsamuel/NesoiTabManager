import assert from 'node:assert/strict';
const module = await import('../background/tree_diagnostic_receiver.js').catch(() => ({}));
assert.equal(typeof module.createDiagnosticReceiver, 'function', '需要有边界校验的诊断IPC接收器');
const events = [];
const incidents = [];
let enabled = true;
const receive = module.createDiagnosticReceiver({ enabled: () => enabled, emit: event => events.push(event), incident: item => incidents.push(item), extensionRoot: 'moz-extension://test/' });
const sender = { url: 'moz-extension://test/ui/sidebar.html' };
receive([{ kind: 'event', payload: { type: 'response-applied', sourceId: 'ui-1', seq: 2, capturedAt: 123, windowId: 1, title: 'secret', nested: { url: 'secret' } } }], sender);
assert.equal(events[0].capturedAt, 123);
assert.equal(typeof events[0].receivedAt, 'number');
assert(!JSON.stringify(events).includes('secret'));
assert.equal(receive([{ kind: 'incident', payload: { type: 'order', signature: 'sig', windowId: 1, ids: [2, 3], status: 'active', evidence: { firstEvidence: { nodes: [{ id: 2, before: { index: 1 }, after: { index: 2 } }] }, orderChanges: [{ id: 2, before: { index: 1 }, after: { index: 2 } }] } } }], sender).accepted, 1);
assert.equal(incidents.length, 1);
assert.equal(incidents[0].evidence.firstEvidence?.nodes[0].before.index, 1, "确认时保留处理中捕获的首次前态");
assert.equal(receive([{kind:'event',payload:{type:'untrusted'}}],{url:'https://example.com/'}).accepted,0);
enabled = false;
assert.equal(receive([{kind:'event',payload:{type:'disabled'}}],sender).accepted,0);
enabled = true;
assert.equal(receive([{kind:'event',payload:{type:'too-big',reason:'x'.repeat(128*1024)}}],sender).accepted,0);
assert(events.some(event => event.type === 'monitor-gap'));
console.log('诊断IPC：来源、字段、长度、时间、总开关校验通过');
